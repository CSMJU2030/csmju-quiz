import type { ReactNode, SVGProps } from "react";

export type IconProps = Omit<SVGProps<SVGSVGElement>, "children"> & {
  /** ไอคอนล้วน (ไม่มีข้อความประกอบ) ต้องส่ง aria-label */
  "aria-label"?: string;
};

export type IconComponent = ((props: IconProps) => ReactNode) & {
  displayName?: string;
};

const SIZE_CLASS = /(^|\s)(h|w|size)-/;

function makeIcon(name: string, children: ReactNode): IconComponent {
  const Component = ({ className, ...props }: IconProps) => {
    const labelled = Boolean(props["aria-label"]);
    const sizing = className && SIZE_CLASS.test(className) ? "" : "h-[1em] w-[1em] ";
    return (
      <svg
        xmlns="http://www.w3.org/2000/svg"
        viewBox="0 0 24 24"
        fill="none"
        stroke="currentColor"
        strokeWidth={1.8}
        strokeLinecap="round"
        strokeLinejoin="round"
        role={labelled ? "img" : undefined}
        aria-hidden={labelled ? undefined : true}
        focusable="false"
        className={`${sizing}inline-block shrink-0 align-[-0.125em] ${className ?? ""}`.trim()}
        {...props}
      >
        {children}
      </svg>
    );
  };
  Component.displayName = name;
  return Component;
}

/** ใช้แทน <FontAwesomeIcon icon={...} /> เมื่อ icon เป็นค่าที่เลือกตอน runtime */
export function Icon({ icon: Glyph, ...props }: IconProps & { icon: IconComponent }) {
  return <Glyph {...props} />;
}

